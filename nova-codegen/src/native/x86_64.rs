    fn andq(&self) -> &str { if self.is_32bit { "andl" } else { "andq" } }
    fn orq(&self) -> &str { if self.is_32bit { "orl" } else { "orq" } }
    fn xorq(&self) -> &str { if self.is_32bit { "xorl" } else { "xorq" } }
