    fn sarq(&self) -> &str { if self.is_32bit { "sarl" } else { "sarq" } }
    fn negq(&self) -> &str { if self.is_32bit { "negl" } else { "negq" } }
    fn notq(&self) -> &str { if self.is_32bit { "notl" } else { "notq" } }
    fn cmpq(&self) -> &str { if self.is_32bit { "cmpl" } else { "cmpq" } }
